// Renders the design mockups in specs/004-mobile-web-client/design/ at 375 px, light and dark, in
// headless Chrome over the DevTools protocol (no npm packages), and checks each screen:
// horizontal overflow, controls whose own box is under 44 x 44 px or overlaps another control,
// text under WCAG AA contrast, text under 14 px, body text under 16 px, console errors.
//
//   node web-react/dev/mockups.mjs [--only graphite,copper,console]
//
// Data comes from design/data/*.json, captured from web-react/dev/mock_api.py. Set CHROME=/path/to/chrome
// if Chrome isn't in /Applications.

import { spawn } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const DESIGN = resolve("specs/004-mobile-web-client/design");
const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : fallback;
};
const DIRECTIONS = arg("only", "graphite,copper,console").split(",");
const SCREENS = [["01-empty", "empty"], ["02-answer", "answer"], ["03-restricted", "restricted"], ["04-source", "source"], ["05-thread", "thread"]];
const THEMES = ["light", "dark"];
const CHROME = process.env.CHROME ?? "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
const PORT = 9334;
const WIDTH = 375;
const HEIGHT = 812;
const BODY_TEXT = ".stmt, .q-text, .callout-text, .side-text, .passage p, .hero-sub, .example span, .missing li, .composer textarea";

const json = (name) => JSON.parse(readFileSync(join(DESIGN, "data", name), "utf8"));
const data = {
  user: { name: "Maria Okafor", first: "Maria", initials: "MO" },
  examples: [
    "Casing bolt torque for FRS-P-0031 after a seal change",
    "E-31 on TAC-C-0143, how do I reset it?",
    "Which oil for the VRS-75 RTM-C-0121?",
    "Rated head of the HCP-200",
  ],
  groups: json("groups.json"),
  q04: json("q04.json"),
  restricted: json("restricted.json"),
  clarify: json("clarify-hcp20.json"),
  followup: json("followup.json"),
  source: json("source-bulletin.json"),
};
writeFileSync(join(DESIGN, "shared", "data.js"),
  `// Generated by web-react/dev/mockups.mjs from design/data/*.json (mock API responses). Don't edit.\nwindow.MOCK_DATA = ${JSON.stringify(data)};\n`);

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const chrome = spawn(CHROME, [
  "--headless=new", `--remote-debugging-port=${PORT}`, `--user-data-dir=${mkdtempSync(join(tmpdir(), "copilot-mock-"))}`,
  "--no-first-run", "--no-default-browser-check", "--disable-gpu", "--hide-scrollbars", "--allow-file-access-from-files", "about:blank",
], { stdio: "ignore" });

async function connect() {
  for (let i = 0; i < 50; i++) {
    try {
      const page = (await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json()).find((t) => t.type === "page");
      if (page) return new Promise((res, rej) => { const ws = new WebSocket(page.webSocketDebuggerUrl); ws.onopen = () => res(ws); ws.onerror = rej; });
    } catch { /* Chrome still starting */ }
    await sleep(200);
  }
  throw new Error("Chrome did not start");
}

const ws = await connect();
let seq = 0;
const waiting = new Map();
const problems = [];
let consoleErrors = [];
ws.onmessage = (ev) => {
  const msg = JSON.parse(ev.data);
  if (msg.id && waiting.has(msg.id)) {
    const { res, rej } = waiting.get(msg.id);
    waiting.delete(msg.id);
    msg.error ? rej(new Error(msg.error.message)) : res(msg.result);
  } else if (msg.method === "Runtime.exceptionThrown") {
    consoleErrors.push(msg.params.exceptionDetails.exception?.description ?? msg.params.exceptionDetails.text);
  } else if (msg.method === "Runtime.consoleAPICalled" && msg.params.type === "error") {
    consoleErrors.push(msg.params.args.map((a) => a.value ?? a.description).join(" "));
  } else if (msg.method === "Log.entryAdded" && msg.params.entry.level === "error") {
    consoleErrors.push(msg.params.entry.text);
  }
};
const send = (method, params = {}) => new Promise((res, rej) => {
  const id = ++seq;
  waiting.set(id, { res, rej });
  ws.send(JSON.stringify({ id, method, params }));
});
const evaluate = async (expression) => {
  const r = await send("Runtime.evaluate", { expression, awaitPromise: true, returnByValue: true });
  if (r.exceptionDetails) throw new Error(r.exceptionDetails.exception?.description ?? r.exceptionDetails.text);
  return r.result.value;
};
const viewport = (height = HEIGHT, width = WIDTH, mobile = true) =>
  send("Emulation.setDeviceMetricsOverride", { width, height, deviceScaleFactor: 2, mobile });

const CHECK = `(() => {
  const out = { overflow: document.documentElement.scrollWidth - ${WIDTH}, small: [], overlap: [], contrast: [], tiny: [], body: [], minRatio: 99 };
  const closed = (el) => { const d = el.closest('details'); return d && !d.open && !el.closest('summary'); };
  const live = (el) => !el.closest('[inert], .visually-hidden') && !closed(el) && el.getClientRects().length > 0;
  const name = (el) => (el.getAttribute('aria-label') || el.textContent || el.placeholder || '').trim().replace(/\\s+/g, ' ').slice(0, 40);
  const controls = [...document.querySelectorAll('a, button, summary, textarea, input')].filter(live);
  const rects = controls.map((el) => [el, el.getBoundingClientRect()]);
  for (const [el, b] of rects) if (b.width < 43.5 || b.height < 43.5) out.small.push(el.className + ' "' + name(el) + '" ' + Math.round(b.width) + 'x' + Math.round(b.height));
  for (let i = 0; i < rects.length; i++) for (let j = i + 1; j < rects.length; j++) {
    const [a, ra] = rects[i], [b, rb] = rects[j];
    if (a.contains(b) || b.contains(a)) continue;
    const w = Math.min(ra.right, rb.right) - Math.max(ra.left, rb.left), h = Math.min(ra.bottom, rb.bottom) - Math.max(ra.top, rb.top);
    if (w > 0.5 && h > 0.5) out.overlap.push('"' + name(a) + '" and "' + name(b) + '" by ' + Math.round(w) + 'x' + Math.round(h));
  }
  const parse = (c) => {
    let m = c.match(/^rgba?\\(([^)]+)\\)/);
    if (m) { const p = m[1].split(/[\\s,\\/]+/).filter(Boolean).map(Number); return [p[0], p[1], p[2], p[3] ?? 1]; }
    m = c.match(/^color\\(srgb ([^)]+)\\)/);
    if (m) { const p = m[1].split(/[\\s\\/]+/).filter(Boolean).map(Number); return [p[0] * 255, p[1] * 255, p[2] * 255, p[3] ?? 1]; }
    return null;
  };
  const over = (top, under) => { const a = top[3]; return [0, 1, 2].map((i) => top[i] * a + under[i] * (1 - a)).concat(1); };
  const bgOf = (el) => {
    const layers = [];
    for (let e = el; e; e = e.parentElement) {
      const c = parse(getComputedStyle(e).backgroundColor);
      if (c && c[3] > 0) { layers.push(c); if (c[3] >= 1) break; }
    }
    let bg = [255, 255, 255, 1];
    for (const l of layers.reverse()) bg = over(l, bg);
    return bg;
  };
  const lum = ([r, g, b]) => { const f = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; }; return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b); };
  const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
  const textEls = [...document.querySelectorAll('body *')].filter((el) => live(el) && [...el.childNodes].some((n) => n.nodeType === 3 && n.textContent.trim()));
  const check = (el, color, label) => {
    const cs = getComputedStyle(el);
    const size = parseFloat(cs.fontSize), bold = parseInt(cs.fontWeight) >= 700;
    const fg = parse(color); if (!fg) return;
    const bg = bgOf(el);
    const r = ratio(over(fg, bg), bg);
    const need = size >= 24 || (size >= 18.66 && bold) ? 3 : 4.5;
    out.minRatio = Math.min(out.minRatio, r);
    if (r < need) out.contrast.push(label + ' ' + r.toFixed(2) + ':1 (needs ' + need + ')');
  };
  for (const el of textEls) {
    const cs = getComputedStyle(el);
    check(el, cs.color, el.tagName.toLowerCase() + '.' + el.className + ' "' + name(el).slice(0, 24) + '"');
    if (parseFloat(cs.fontSize) < 14) out.tiny.push(el.className + ' "' + name(el).slice(0, 24) + '" ' + cs.fontSize);
  }
  for (const t of document.querySelectorAll('textarea')) if (live(t)) check(t, getComputedStyle(t, '::placeholder').color, 'placeholder "' + t.placeholder + '"');
  for (const el of document.querySelectorAll(${JSON.stringify(BODY_TEXT)})) if (live(el) && parseFloat(getComputedStyle(el).fontSize) < 16) out.body.push(el.className + ' "' + name(el).slice(0, 24) + '" ' + getComputedStyle(el).fontSize);
  return out;
})()`;

const summary = {};
try {
  await send("Page.enable");
  await send("Runtime.enable");
  await send("Log.enable");
  for (const dir of DIRECTIONS) {
    summary[dir] = { minRatio: 99 };
    for (const theme of THEMES) {
      await send("Emulation.setEmulatedMedia", { features: [{ name: "prefers-color-scheme", value: theme }] });
      for (const [file, screen] of SCREENS) {
        const where = `${dir}/${file}-${theme}`;
        consoleErrors = [];
        await viewport();
        const url = `${pathToFileURL(join(DESIGN, dir, "index.html")).href}?screen=${screen}`;
        await send("Page.navigate", { url });
        for (let i = 0; i < 50 && !(await evaluate("document.readyState === 'complete' && !!document.querySelector('.app')")); i++) await sleep(100);
        await sleep(150);
        // Checked at full height, so the sticky composer doesn't sit on top of the thread.
        if (screen !== "source") {
          await viewport(Math.max(HEIGHT, await evaluate("Math.ceil(document.documentElement.scrollHeight)")));
          await sleep(120);
        }
        const r = await evaluate(CHECK);
        if (r.overflow > 0) problems.push(`${where}: horizontal overflow ${r.overflow}px`);
        for (const s of r.small) problems.push(`${where}: control under 44px: ${s}`);
        for (const s of r.overlap) problems.push(`${where}: controls overlap: ${s}`);
        for (const s of r.contrast) problems.push(`${where}: contrast ${s}`);
        for (const s of r.tiny) problems.push(`${where}: text under 14px: ${s}`);
        for (const s of r.body) problems.push(`${where}: body text under 16px: ${s}`);
        for (const e of consoleErrors) problems.push(`${where}: console error: ${e}`);
        summary[dir].minRatio = Math.min(summary[dir].minRatio, r.minRatio);
        const { data: png } = await send("Page.captureScreenshot", { format: "png" });
        writeFileSync(join(DESIGN, dir, `${file}-${theme}.png`), Buffer.from(png, "base64"));
      }
    }
    // One overview image per direction: light row above dark row, at half scale.
    const cells = THEMES.map((t) => `<div class="row"><p>${t}</p>${SCREENS.map(([f, s]) =>
      `<figure><img src="${f}-${t}.png"><figcaption>${s}</figcaption></figure>`).join("")}</div>`).join("");
    const overview = join(DESIGN, dir, "overview.html");
    writeFileSync(overview, `<!doctype html><meta charset="utf-8"><title>${dir} overview</title><style>
      body{margin:0;padding:16px;background:#d9dbe0;font:600 15px system-ui}.row{display:flex;gap:12px;align-items:flex-start;margin-bottom:16px}
      .row>p{writing-mode:vertical-rl;transform:rotate(180deg);margin:0}figure{margin:0;width:188px}img{width:188px;display:block;border-radius:8px;box-shadow:0 1px 4px #0003}
      figcaption{margin-top:4px}</style><h1 style="margin:0 0 12px;font-size:20px">${dir}</h1>${cells}`);
    await send("Emulation.clearDeviceMetricsOverride");
    await viewport(800, 1040, false);
    await send("Page.navigate", { url: pathToFileURL(overview).href });
    await sleep(600);
    const h = await evaluate("Math.ceil(document.documentElement.scrollHeight)");
    await viewport(h, 1040, false);
    await sleep(300);
    const { data: png } = await send("Page.captureScreenshot", { format: "png" });
    writeFileSync(join(DESIGN, dir, "overview.png"), Buffer.from(png, "base64"));
    console.log(`${dir}: ${SCREENS.length * THEMES.length} screens, lowest text contrast ${summary[dir].minRatio.toFixed(2)}:1`);
  }
} catch (err) {
  problems.push(`run aborted: ${err.message}`);
} finally {
  chrome.kill();
}
if (problems.length) {
  console.log(`\n${problems.length} problem(s):`);
  for (const p of problems) console.log(`  - ${p}`);
  process.exitCode = 1;
} else {
  console.log("\nall mockups at 375 px: no overflow, every control at least 44 x 44 px with no overlaps, text AA in both themes, body text 16 px or more");
}
