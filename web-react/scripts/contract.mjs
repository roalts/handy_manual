// npm run contract: regenerate src/lib/contract.ts from the AnswerResponse JSON Schema, and write
// src/lib/contract.examples.ts so `tsc` checks every example response (contract examples and
// the mock's own fixtures) against the generated types.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = fileURLToPath(new URL("../../", import.meta.url));
const examplesDir = `${root}specs/contracts/examples/`;
const fixturesDir = `${root}web-react/dev/fixtures/`;
const out = fileURLToPath(new URL("../src/lib/", import.meta.url));

const banner = (what) =>
  `// Generated by \`npm run contract\` from specs/contracts/examples/answer-response.schema.json${what}. Do not edit.\n`;

const schema = JSON.parse(readFileSync(`${examplesDir}answer-response.schema.json`, "utf8"));
const types = await compile(schema, "AnswerResponse", {
  bannerComment: banner(""),
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { semi: true, singleQuote: false, printWidth: 110 },
});
writeFileSync(`${out}contract.ts`, types);

const examples = [
  ...readdirSync(examplesDir).filter((f) => f.endsWith(".json") && !f.endsWith(".schema.json")).map((f) => [f, examplesDir]),
  ...readdirSync(fixturesDir).filter((f) => /^mock_.*\.json$/.test(f)).map((f) => [f, fixturesDir]),
].sort(([a], [b]) => a.localeCompare(b));

const name = (f) => f.replace(/\.json$/, "").replace(/[^a-zA-Z0-9]+(.)/g, (_, c) => c.toUpperCase());
const body = examples
  .map(([f, dir]) => `export const ${name(f)} = ${JSON.stringify(JSON.parse(readFileSync(dir + f, "utf8")), null, 2)} satisfies AnswerResponse;\n`)
  .join("\n");
writeFileSync(
  `${out}contract.examples.ts`,
  `${banner(" and the example responses")}\nimport type { AnswerResponse } from "./contract";\n\n${body}`,
);
console.log(`contract.ts and ${examples.length} examples written`);
